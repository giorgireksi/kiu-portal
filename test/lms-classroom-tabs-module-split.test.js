        expect(routeCss).toContain('.lms-attendance-panel {');
        expect(routeCss).toContain('.lms-attendance-table-shell {');
        expect(routeCss).toContain('.lms-attendance-table {');
        expect(routeCss).toContain('.lms-attendance-status-badge {');

