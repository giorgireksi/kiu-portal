        expect(classroomSource).toContain('function switchLMSTab(tab)');
        expect(classroomSource).toContain('function isLmsElementShown(element) {');
        expect(classroomSource).toContain('return Boolean(element) && !element.hidden;');
        expect(classroomSource).toContain('monitoringTab.hidden = ![USER_ROLES.PROFESSOR, USER_ROLES.TA, USER_ROLES.ADMIN].includes(effectiveRole);');
