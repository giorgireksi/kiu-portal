        expect(classroomSource).toContain('class="lms-bulk-head lms-bulk-head--plain"');
        expect(classroomSource).toContain('class="lms-route-panel lms-route-panel-compact lms-bulk-panel is-collapsed"');
        expect(classroomSource).toContain('class="lms-route-card lms-route-panel-compact lms-bulk-card"');
        expect(classroomSource).toContain('class="lms-route-card lms-route-panel-compact lms-session-official-card"');
        expect(classroomSource).toContain('class="lms-route-panel lms-route-panel-compact lms-session-marker-composer is-collapsed"');
        expect(classroomSource).toContain('class="lms-route-card lms-route-panel-compact lms-session-marker-card is-');
        expect(classroomSource).toContain('class="lms-route-card lms-route-panel-compact lms-member-card"');
        expect(classroomSource).toContain('class="lms-route-card-head lms-route-card-head-mb-14 lms-member-card-head"');
